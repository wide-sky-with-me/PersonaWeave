"""Shipped CPU-to-GPU upgrade utility; preserves user data and can resume interrupted file replacement."""

import hashlib
import json
import shutil
from pathlib import Path


def digest(path):
    """Hash a shipped file without loading model weights into memory."""
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def owned_path(root, name):
    """Constrain update manifests to application files; user state is never an update destination."""
    base = root.resolve()
    path = (base / name).resolve()
    if not path.is_relative_to(base) or path == base or "\\" in name or ":" in name:
        raise ValueError("升级清单包含非法路径")
    # Check the resolved relative name too, so runtime/../.env and symlinks cannot
    # disguise a private-data destination while remaining inside the application root.
    relative = path.relative_to(base).as_posix()
    if relative.startswith(("outputs/", "logs/", ".env")) or (
        relative.startswith("data/") and not relative.startswith(("data/test_target/", "data/test_images/"))
    ):
        raise ValueError("升级清单包含非法路径")
    return path


def apply_update(root, payload, *, label="GPU 升级"):
    """Validate all inputs before writing, hold the application lock, and publish the manifest last."""
    from api.portable import instance_lock

    update = json.loads((payload / "update.json").read_text(encoding="utf-8"))
    old = update["base_files"]
    new_manifest_path = payload / "manifest.json"
    if digest(new_manifest_path) != update["new_manifest_sha256"]:
        raise ValueError("升级包清单校验失败，请重新解压")
    new = json.loads(new_manifest_path.read_text(encoding="utf-8"))["files"]
    with instance_lock(root) as acquired:
        if not acquired:
            raise RuntimeError("请先关闭正在运行的工作台，再执行升级")
        installed = digest(root / "manifest.json")
        if installed == update["new_manifest_sha256"]:
            print(f"已安装此{label}版本，无需重复升级。")
            return
        if installed != update["base_manifest_sha256"]:
            raise ValueError("此升级包与当前版本不匹配，请使用对应版本的完整包")
        changed = {name: value for name, value in new.items() if old.get(name) != value}
        # Checking unchanged dependencies adds minutes of Windows metadata I/O without
        # protecting a write. Regenerated bytecode is removed by directory below.
        removed = {name for name in old.keys() - new.keys() if not name.endswith(".pyc")}
        destinations = {name: owned_path(root, name) for name in changed.keys() | removed}
        # Validate the complete payload first. Re-run may find either old or already replaced
        # bytes, but unrelated user edits must never be silently overwritten.
        print(f"正在校验全部{label}文件...", flush=True)
        for name, expected in changed.items():
            path = owned_path(payload / "files", name)
            if not path.is_file() or digest(path) != expected:
                raise ValueError(f"升级文件校验失败：{name}，请重新解压升级包")
        print("正在检查需要替换的旧程序文件...", flush=True)
        for name, path in destinations.items():
            if path.exists() and digest(path) not in {old.get(name), new.get(name)}:
                raise ValueError(f"程序文件已被修改：{name}；未覆盖，请使用完整 GPU 包")
        print(f"正在安装{label}，请勿关闭窗口...", flush=True)
        for name in changed:
            path = destinations[name]
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = path.with_name(path.name + ".gpu-tmp")
            shutil.copyfile(owned_path(payload / "files", name), temporary)
            temporary.replace(path)
        for name in removed:
            destinations[name].unlink(missing_ok=True)
        for directory in ("api", "core", "utils", "runtime"):
            for cache in (root / directory).rglob("__pycache__"):
                if cache.is_dir():
                    shutil.rmtree(cache)
        temporary = root / "manifest.gpu-tmp"
        shutil.copyfile(new_manifest_path, temporary)
        temporary.replace(root / "manifest.json")
        shutil.rmtree(payload / "files")
        print(f"{label}完成。原有 AI 配置、工程和历史已保留，临时安装文件已清理。请双击 Start.cmd。")


if __name__ == "__main__":
    payload = Path(__file__).resolve().parent
    try:
        apply_update(payload.parent, payload)
    except (OSError, ValueError, RuntimeError, KeyError) as exc:
        print(f"升级未完成：{exc}")
        raise SystemExit(1) from exc
